export function analysisLibraryStatus(method) {
  return method.tools.length ? "tool" : method.posts.length ? "guide" : "reference";
}

export function filterAnalysisLibrary({ query = "", status = "all", locale = "ko" } = {}) {
  const terms = String(query).normalize("NFKC").toLocaleLowerCase().trim().split(/\s+/).filter(Boolean);
  return MARKETING_ANALYSIS_DOMAINS.map((group) => ({
    ...group,
    methods: group.methods.filter((entry) => {
      if (status !== "all" && analysisLibraryStatus(entry) !== status) return false;
      // 두 언어의 학술 용어도 검색한다. 화면 언어만 바꿔도 같은 방법을 찾을 수 있어야 한다.
      const text = [group.title[locale], ...Object.values(entry.title), ...Object.values(entry.question),
        ...Object.values(entry.input), ...Object.values(entry.limit), entry.id,
        ...entry.references.map((id) => ANALYSIS_REFERENCES[id].title)].join(" ").normalize("NFKC").toLocaleLowerCase();
      return terms.every((term) => text.includes(term));
    }),
  })).filter((group) => group.methods.length);
}
